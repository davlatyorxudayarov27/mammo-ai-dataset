"""Dataset / annotation exporters: YOLO, Pascal VOC, CSV, and segmentation masks.

All builders are pure functions that take a normalized ``images`` list and return
``bytes`` (or, for CSV, ``bytes`` of UTF-8 text). An ``image`` dict looks like::

    {
        "source": "upload" | "local",
        "ref": "<id or relative path>",
        "rows": int,            # pixel height (0 if unknown)
        "cols": int,            # pixel width  (0 if unknown)
        "annotations": [ {bbox|points, label, labels, type, ...}, ... ],
    }

Bounding boxes are normalized ``[x, y, w, h]`` (top-left + size, 0..1).
Polygons are ``points`` = ``[[x, y], ...]`` normalized.

Multi-label: an annotation may carry ``labels: [...]``; ``label`` is the primary
(first) label kept for backward compatibility. ``ann_labels()`` tolerates both.
"""
from __future__ import annotations

import csv
import io
import os
import tempfile
import zipfile
from datetime import datetime, timezone
from xml.sax.saxutils import escape


def ann_labels(a: dict) -> list[str]:
    """Return all labels for an annotation, tolerating old single-label records."""
    ls = a.get("labels")
    if isinstance(ls, list) and ls:
        return [str(x) for x in ls if x]
    lab = a.get("label")
    return [str(lab)] if lab else []


def _safe_stem(ref: str) -> str:
    """Turn a ref (which may be a path) into a flat, filesystem-safe stem."""
    stem = str(ref or "annotation").replace("\\", "/").split("/")[-1]
    if stem.lower().endswith(".dcm"):
        stem = stem[:-4]
    out = "".join(ch if (ch.isalnum() or ch in "-_.") else "_" for ch in stem)
    return out or "annotation"


# --------------------------------------------------------------------------- #
# YOLO                                                                        #
# --------------------------------------------------------------------------- #
def _yolo_yaml(label_names: list[str]) -> str:
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(label_names))
    return (
        "# YOLO dataset config generated by MAMOGRAF\n"
        "path: .\n"
        "train: images\n"
        "val: images\n"
        f"nc: {len(label_names)}\n"
        "names:\n"
        f"{names}\n"
    )


def build_yolo_zip(images: list[dict], label_names: list[str]) -> bytes:
    """YOLO detection dataset: one ``labels/<stem>.txt`` per image + classes/yaml.

    Each line: ``<class> <cx> <cy> <w> <h>`` (all normalized). A multi-label
    annotation produces one line per label (shared geometry).
    """
    idx = {name: i for i, name in enumerate(label_names)}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("classes.txt", "\n".join(label_names) + "\n")
        z.writestr("data.yaml", _yolo_yaml(label_names))
        z.writestr("README.txt",
                   "YOLO detection format. Each labels/<image>.txt line:\n"
                   "<class_index> <x_center> <y_center> <width> <height>  (normalized 0..1)\n")
        for im in images:
            lines: list[str] = []
            for a in im.get("annotations", []):
                bbox = a.get("bbox")
                if not bbox or len(bbox) != 4:
                    continue
                x, y, w, h = bbox
                cx, cy = x + w / 2.0, y + h / 2.0
                for lab in ann_labels(a):
                    if lab in idx:
                        lines.append(f"{idx[lab]} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}")
            stem = _safe_stem(im.get("ref"))
            z.writestr(f"labels/{stem}.txt", ("\n".join(lines) + "\n") if lines else "")
    return buf.getvalue()


# --------------------------------------------------------------------------- #
# Pascal VOC                                                                  #
# --------------------------------------------------------------------------- #
def _voc_xml(im: dict) -> str:
    rows = int(im.get("rows") or 0)
    cols = int(im.get("cols") or 0)
    ref = im.get("ref") or "annotation"
    stem = _safe_stem(ref)
    objs: list[str] = []
    for a in im.get("annotations", []):
        bbox = a.get("bbox")
        if not bbox or len(bbox) != 4:
            continue
        x, y, w, h = bbox
        if cols and rows:
            xmin = int(round(x * cols)); ymin = int(round(y * rows))
            xmax = int(round((x + w) * cols)); ymax = int(round((y + h) * rows))
        else:
            # No pixel dims known: fall back to a 1000-unit canvas so coords stay usable.
            xmin = int(round(x * 1000)); ymin = int(round(y * 1000))
            xmax = int(round((x + w) * 1000)); ymax = int(round((y + h) * 1000))
        for lab in ann_labels(a):
            objs.append(
                "  <object>\n"
                f"    <name>{escape(lab)}</name>\n"
                "    <pose>Unspecified</pose>\n"
                "    <truncated>0</truncated>\n"
                "    <difficult>0</difficult>\n"
                "    <bndbox>\n"
                f"      <xmin>{xmin}</xmin>\n"
                f"      <ymin>{ymin}</ymin>\n"
                f"      <xmax>{xmax}</xmax>\n"
                f"      <ymax>{ymax}</ymax>\n"
                "    </bndbox>\n"
                "  </object>"
            )
    return (
        "<annotation>\n"
        f"  <folder>{escape(str(im.get('source') or ''))}</folder>\n"
        f"  <filename>{escape(stem)}.dcm</filename>\n"
        f"  <path>{escape(str(ref))}</path>\n"
        "  <source><database>MAMOGRAF</database></source>\n"
        "  <size>\n"
        f"    <width>{cols}</width>\n"
        f"    <height>{rows}</height>\n"
        "    <depth>1</depth>\n"
        "  </size>\n"
        "  <segmented>0</segmented>\n"
        + ("\n".join(objs) + "\n" if objs else "")
        + "</annotation>\n"
    )


def build_voc_zip(images: list[dict]) -> bytes:
    """Pascal VOC: one XML per image. Multi-label → multiple ``<object>`` blocks."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for im in images:
            z.writestr(f"{_safe_stem(im.get('ref'))}.xml", _voc_xml(im))
    return buf.getvalue()


# --------------------------------------------------------------------------- #
# CSV (one row per annotation, multi-label column)                            #
# --------------------------------------------------------------------------- #
CSV_HEADER = [
    "source", "ref", "annotation_id", "type",
    "label", "labels", "bi_rads", "status", "frame",
    "x_norm", "y_norm", "w_norm", "h_norm",
    "x_px", "y_px", "w_px", "h_px", "points_count",
    "created_by", "reviewed_by", "note",
]


def build_csv(images: list[dict]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(CSV_HEADER)
    for im in images:
        rows = int(im.get("rows") or 0)
        cols = int(im.get("cols") or 0)
        for a in im.get("annotations", []):
            bbox = (list(a.get("bbox") or []) + [0, 0, 0, 0])[:4]
            x, y, wn, hn = bbox
            labs = ann_labels(a)
            if rows and cols:
                px = [round(x * cols, 1), round(y * rows, 1),
                      round(wn * cols, 1), round(hn * rows, 1)]
            else:
                px = ["", "", "", ""]
            pts = a.get("points") or []
            w.writerow([
                im.get("source", ""), im.get("ref", ""), a.get("id", ""),
                a.get("type", "bbox"),
                labs[0] if labs else "", ";".join(labs),
                a.get("bi_rads", ""), a.get("status", "draft"), a.get("frame", 0),
                x, y, wn, hn, px[0], px[1], px[2], px[3],
                len(pts) if a.get("type") == "polygon" else "",
                a.get("created_by", ""), a.get("reviewed_by", ""),
                (str(a.get("note") or "").replace("\n", " ").replace("\r", " ")
                 + (" · AI batch (izoh)" if a.get("ai_source") else "")).strip(" ·"),
            ])
    # BOM so Excel opens UTF-8 correctly.
    return ("﻿" + buf.getvalue()).encode("utf-8")


# --------------------------------------------------------------------------- #
# Segmentation masks (PNG / NIfTI) — per image                                #
# --------------------------------------------------------------------------- #
def build_label_mask(annotations: list[dict], rows: int, cols: int,
                     label_index: dict[str, int]):
    """Return a 2D uint8/uint16 label-indexed mask (0 = background).

    On overlap the later annotation wins. Multi-label annotations are painted
    with their primary (first) label's class index.
    """
    import numpy as np

    if not rows or not cols:
        raise ValueError("image dimensions unknown; cannot build mask")
    max_cls = max(label_index.values()) if label_index else 0
    dtype = np.uint8 if max_cls < 256 else np.uint16
    mask = np.zeros((int(rows), int(cols)), dtype=dtype)

    try:
        import cv2
        has_cv2 = True
    except Exception:
        has_cv2 = False
        from PIL import Image, ImageDraw

    if not has_cv2:
        pil = Image.fromarray(mask)
        draw = ImageDraw.Draw(pil)

    for a in annotations:
        labs = ann_labels(a)
        if not labs:
            continue
        cls = label_index.get(labs[0])
        if not cls:
            continue
        if a.get("type") == "polygon" and a.get("points"):
            poly = [(float(px) * cols, float(py) * rows) for px, py in a["points"]]
            if has_cv2:
                pts = np.array([[int(round(px)), int(round(py))] for px, py in poly],
                               dtype=np.int32)
                cv2.fillPoly(mask, [pts], int(cls))
            else:
                draw.polygon([(int(round(px)), int(round(py))) for px, py in poly],
                             fill=int(cls))
        else:
            bbox = a.get("bbox")
            if not bbox or len(bbox) != 4:
                continue
            x, y, w, h = bbox
            x0, y0 = int(round(x * cols)), int(round(y * rows))
            x1, y1 = int(round((x + w) * cols)), int(round((y + h) * rows))
            if has_cv2:
                cv2.rectangle(mask, (x0, y0), (x1, y1), int(cls), thickness=-1)
            else:
                draw.rectangle([x0, y0, x1, y1], fill=int(cls))

    if not has_cv2:
        import numpy as np
        mask = np.array(pil, dtype=dtype)
    return mask


def mask_to_png_bytes(mask) -> bytes:
    from PIL import Image
    arr = mask
    mode = "L" if arr.dtype.itemsize == 1 else "I;16"
    img = Image.fromarray(arr, mode=mode)
    bio = io.BytesIO()
    img.save(bio, format="PNG")
    return bio.getvalue()


def mask_to_nifti_bytes(mask) -> bytes:
    import nibabel as nib
    import numpy as np

    arr = np.asarray(mask)
    if arr.ndim == 2:
        arr = arr[:, :, None]
    img = nib.Nifti1Image(arr.astype(np.uint16), affine=np.eye(4))
    with tempfile.TemporaryDirectory() as td:
        fp = os.path.join(td, "mask.nii.gz")
        nib.save(img, fp)
        with open(fp, "rb") as f:
            return f.read()


def mask_legend(label_index: dict[str, int]) -> dict[int, str]:
    """Map class index → label name (useful as a sidecar JSON)."""
    return {v: k for k, v in label_index.items()}
